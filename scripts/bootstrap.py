"""Interactive first-run setup for ARMAMENT's local Docker services."""
from __future__ import annotations

import getpass
import os
import secrets
import shutil
import subprocess
import sys
import time
import tempfile
import venv
from contextlib import contextmanager
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


@contextmanager
def _bootstrap_lock():
    """Serialize bootstrap across processes on Windows and POSIX."""
    with (ROOT / ".bootstrap.lock").open("a+b") as handle:
        if os.name == "nt":
            import msvcrt
            handle.seek(0)
            if not handle.read(1):
                handle.write(b"0")
                handle.flush()
            handle.seek(0)
            msvcrt.locking(handle.fileno(), msvcrt.LK_LOCK, 1)
            try:
                yield
            finally:
                handle.seek(0)
                msvcrt.locking(handle.fileno(), msvcrt.LK_UNLCK, 1)
        else:
            import fcntl
            fcntl.flock(handle.fileno(), fcntl.LOCK_EX)
            try:
                yield
            finally:
                fcntl.flock(handle.fileno(), fcntl.LOCK_UN)


def _write_env_atomically(path: Path, values: list[str]) -> None:
    fd, temporary = tempfile.mkstemp(prefix=".env.", suffix=".tmp", dir=ROOT)
    try:
        os.fchmod(fd, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write("\n".join(values))
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, path)
        try:
            path.chmod(0o600)
        except OSError:
            pass
    except BaseException:
        try:
            os.unlink(temporary)
        except FileNotFoundError:
            pass
        raise


def _docker_compose() -> list[str]:
    if not shutil.which("docker"):
        raise SystemExit("Docker was not found. Install Docker Desktop/Engine first.")
    result = subprocess.run(
        ["docker", "compose", "version"], cwd=ROOT, capture_output=True, text=True
    )
    if result.returncode:
        raise SystemExit(
            "Docker Compose v2 is required. Update your Docker installation."
        )
    return ["docker", "compose"]


def _wait_for_health(url: str, timeout: int = 60) -> bool:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        try:
            with urllib.request.urlopen(url, timeout=2) as response:
                if response.status == 200:
                    return True
        except (urllib.error.URLError, TimeoutError, OSError):
            time.sleep(2)
    return False


def main() -> int:
    with _bootstrap_lock():
        return _main_locked()


def _main_locked() -> int:
    env_path = ROOT / ".env"
    if env_path.exists():
        raise SystemExit(
            ".env already exists. Refusing to overwrite credentials; back it up "
            "before running setup again."
        )

    _docker_compose()
    venv_dir = ROOT / ".venv"
    if not venv_dir.exists():
        venv.EnvBuilder(with_pip=True).create(venv_dir)
    venv_python = (
        venv_dir / "Scripts" / "python.exe"
        if os.name == "nt"
        else venv_dir / "bin" / "python"
    )
    bin_dir = venv_python.parent
    environment = os.environ.copy()
    environment["VIRTUAL_ENV"] = str(venv_dir)
    environment["PATH"] = str(bin_dir) + os.pathsep + environment.get("PATH", "")
    subprocess.run(["pip", "install", "--upgrade", "pip"], cwd=ROOT, env=environment, check=True)
    subprocess.run(["pip", "install", "-e", "."], cwd=ROOT, env=environment, check=True)
    print(
        "\\nSecurity notice: ARMAMENT needs ports 8931 and 8932 reachable from "
        "your TrueForge container. The default publishes them on all host "
        "interfaces. Restrict both ports with your host firewall; never expose "
        "them to the public internet."
    )
    firewall_confirmed = (
        input("Have you restricted access to these ports? [y/N]: ")
        .strip()
        .lower()
        in {"y", "yes"}
    )
    if not firewall_confirmed:
        raise SystemExit(
            "Setup cancelled. Configure host firewall access before continuing."
        )
    groq_key = getpass.getpass("Groq API key (input hidden): ").strip()
    if not groq_key:
        raise SystemExit("A Groq API key is required.")
    daytona_key = getpass.getpass(
        "Daytona API key (optional; press Enter to skip): "
    ).strip()

    auth_token = secrets.token_urlsafe(48)
    bind_address = os.environ.get("ARMAMENT_BIND_ADDRESS", "0.0.0.0")
    values = [
        "# Generated by scripts/bootstrap.py. Keep this file private.",
        f"ARMAMENT_BIND_ADDRESS={bind_address}",
        "SENTINEL_HOST=0.0.0.0",
        "PORT=8931",
        f"SENTINEL_AUTH_TOKEN={auth_token}",
        f"GROQ_SHIM_AUTH_TOKEN={auth_token}",
        "SENTINEL_LABEL=sentinel.managed=true",
        f"GROQ_API_KEY={groq_key}",
        f"DAYTONA_API_KEY={daytona_key}",
        "GROQ_SHIM_HOST=0.0.0.0",
        "GROQ_SHIM_PORT=8932",
        "TRUEFORGE_URL=http://localhost:8791",
        "SENTINEL_MCP_URL=http://host.docker.internal:8931/mcp",
        "GROQ_BASE_URL=http://host.docker.internal:8932/v1",
        "",
    ]
    _write_env_atomically(env_path, values)

    try:
        subprocess.run(["docker", "compose", "up", "--build", "-d"], cwd=ROOT, check=True)
    except subprocess.CalledProcessError as exc:
        raise SystemExit(
            "Docker Compose failed. Inspect docker compose logs; .env was preserved."
        ) from exc

    probe_host = "localhost" if bind_address in {"0.0.0.0", "::"} else bind_address
    sentinel_ok = _wait_for_health(f"http://{probe_host}:8931/healthz")
    shim_ok = _wait_for_health(f"http://{probe_host}:8932/healthz")
    print("\nARMAMENT local services:")
    print(f"  sentinel-ops: {'healthy' if sentinel_ok else 'NOT READY'}")
    print(f"  groq-shim:    {'healthy' if shim_ok else 'NOT READY'}")
    if not (sentinel_ok and shim_ok):
        print("Inspect logs with: docker compose logs --tail=100")
        return 1

    print("\nNext: install/start the separate TrueForge harness, then run:")
    print("  Windows: .\\.venv\\Scripts\\python.exe scripts/provision.py")
    print("  macOS/Linux: .venv/bin/python scripts/provision.py")
    print("TrueForge must reach host.docker.internal on ports 8931 and 8932.")
    print("Only label containers you explicitly authorize ARMAMENT to manage.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
